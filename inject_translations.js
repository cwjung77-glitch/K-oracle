for (const lang of Object.keys(extraTranslations)) {
  const extraObj = extraTranslations[lang];
  const blockStartRegex = new RegExp("\\b" + lang + ": \\{\\n", 'g');
  const insertStr = Object.entries(extraObj).map(([k, v]) => `    ${k}: "${v.replace(/"/g, '\\"')}",`).join('\\n') + '\\n';
  i18nCode = i18nCode.replace(blockStartRegex, lang + ": {\\n" + insertStr);
}

fs.writeFileSync('src/locales/i18n.js', i18nCode);
